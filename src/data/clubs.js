const LEAGUE_BY_ID = new Map(LEAGUES.map((league) => [league.id, league]));

export const ALL_CLUBS = LEAGUES.flatMap((league) =>
  league.teams.map((team) => ({ ...team, leagueId: league.id })),
);

const CLUB_BY_ID = new Map(ALL_CLUBS.map((club) => [club.id, club]));

export const getLeague = (id) => LEAGUE_BY_ID.get(id);

export const getClub = (id) => CLUB_BY_ID.get(id);

/** Nível médio do plantel de um clube (escala de overall). */
export function squadRating(clubId) {
  const club = getClub(clubId);
  if (!club) return 55;
  const league = getLeague(club.leagueId);
  const base = 38 + club.prestige * 0.46;
  const leagueBias = ((league?.level ?? 60) - 60) * 0.12;
  return Math.round(base + leagueBias);
}

/** Salário semanal típico por nível de clube e importância do jogador. */
export function salaryBand(clubId) {
  const club = getClub(clubId);
  const league = getLeague(club?.leagueId);
  const prestige = club?.prestige ?? 40;
  const richFactor = league?.richLeague ? 1.8 : 1;
  const youthFactor = league?.youth ? 0.08 : 1;
  const weekly = 180 * Math.pow(1.072, prestige) * richFactor * youthFactor;
  return Math.max(400, Math.round(weekly));
}
