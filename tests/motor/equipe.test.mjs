import { Game } from '../../src/core/game.js';
import { trainingOptionsFor } from '../../src/engine/training.js';
import { weeklyExpenses } from '../../src/engine/finance.js';
import { effectiveAttributes } from '../../src/engine/overall.js';
const ok = (c, m) => { console.log(c ? 'ok -' : 'FALHOU -', m); if (!c) process.exitCode = 1; };
const g = new Game();
g.createCareer({ firstName: 'A', lastName: 'B', position: 'ATA', nationality: 'BRA', traits: ['driblador', 'midiatico'], groupPoints: {}, appearance: {} });
g.acceptTrial(g.state.trials.offers[0].id);
const p = g.state.player;
p.money = 0;
ok(!g.buyItem('chuteira').ok, 'sem dinheiro não compra');
p.money = 10_000_000;
const before = effectiveAttributes(p).shotPower, ovBefore = p.overall;
ok(g.buyItem('chuteira').ok && p.money === 10_000_000 - 8_000, 'compra chuteira e desconta €8 mil');
ok(effectiveAttributes(p).shotPower === before + 1, 'chuteira dá +1 em força do chute');
ok(!g.buyItem('chuteira').ok, 'não compra o mesmo item duas vezes');
ok(!g.buyItem('luvas').ok, 'luvas só para goleiro');
const base = trainingOptionsFor(p).map((o) => o.id);
ok(!base.includes('mentor') && !base.includes('video'), 'treinos novos começam travados');
const exp0 = weeklyExpenses(p);
ok(g.buyItem('mentor').ok && p.money === 10_000_000 - 8_000 - 120_000, 'mentor cobra 4 semanas adiantadas');
ok(weeklyExpenses(p) === exp0 + 30_000, 'mentor entra nos gastos da semana');
ok(trainingOptionsFor(p).some((o) => o.id === 'mentor'), 'mentor libera o treino com o mentor');
g.buyItem('academia_casa'); g.buyItem('analista'); g.buyItem('centro_recuperacao');
ok(['academia_casa', 'video', 'crioterapia'].every((id) => trainingOptionsFor(p).some((o) => o.id === id)), 'academia, análise de vídeo e crioterapia liberados');
p.skillPoints = 0; g.state.week.step = 'treino';
const r = g.chooseTraining('mentor');
ok(r.option.id === 'mentor' && r.skillPoints >= 2 && r.xp > 30, `treino com mentor: ${r.xp} XP, ${r.skillPoints} pontos`);
g.state.week.step = 'treino'; p.life.fitness = 40;
g.chooseTraining('crioterapia');
ok(p.life.fitness >= 40 + 18, `crioterapia recupera forma (agora ${p.life.fitness})`);
ok(g.dismissStaff('mentor').ok && !trainingOptionsFor(p).some((o) => o.id === 'mentor') && weeklyExpenses(p) === exp0 + 5_000, 'dispensar o mentor tira o treino e o custo');
